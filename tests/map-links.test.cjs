function fixture(agent) {
    const assigned = [], timers = new Map(), docEvents = new Map(), winEvents = new Map(); let id = 0;
    const doc = { visibilityState:'visible', addEventListener:(k,v)=>docEvents.set(k,v), removeEventListener:(k,v)=>{ if(docEvents.get(k)===v)docEvents.delete(k); } };
    const win = { location:{ assign:url=>assigned.push(url) }, setTimeout:fn=>{ timers.set(++id,fn); return id; }, clearTimeout:i=>timers.delete(i), addEventListener:(k,v)=>winEvents.set(k,v), removeEventListener:(k,v)=>{if(winEvents.get(k)===v)winEvents.delete(k);} };
    const handler = Maps.createNavigation({ window:win, document:doc, navigator:agent });
    const anchor = { href:links.href, getAttribute:()=>links.appUrl };
    const event = { button:0, target:{ closest:()=>anchor }, preventDefault(){ this.defaultPrevented = true; } };
    return { handler, event, assigned, timers, docEvents, winEvents, doc };
}
